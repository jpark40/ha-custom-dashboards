const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const names = ['blue-iris-timeline-card.js', 'purobot-timeline-card.js', 'front-door-timeline-card.js', 'vehicle-status-card.js'];
const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
let result = `// Jeff HA dashboards bundle v${version}. Generated by scripts/build.js.\n`;
for (const name of names) result += `\n// ${name}\n(() => {\n${fs.readFileSync(path.join(root, 'src', name), 'utf8').replaceAll('__PACKAGE_VERSION__', version)}\n})();\n`;
result += `\nconsole.info('Jeff HA dashboards v${version} loaded');\n`;
fs.mkdirSync(path.join(root, 'dist'), {recursive:true});
fs.writeFileSync(path.join(root, 'dist', 'ha-custom-dashboards.js'), result);
